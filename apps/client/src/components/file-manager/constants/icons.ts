/** 取最后一个扩展名，统一小写；无扩展名返回空串。 */
function extOf(name: string): string {
  const i = name.lastIndexOf(".");
  // 前导点的隐藏文件（.env）不算扩展名
  if (i <= 0) return "";
  return name.slice(i + 1).toLowerCase();
}

/** 文件图标名；未命中返回默认文件图标。 */
export function resolveFileIcon(name: string): string {
  const lower = name.toLowerCase();
  return BY_NAME[lower] ?? BY_EXT[extOf(name)] ?? DEFAULT_FILE;
}

/** 当前注册进 iconify 的图标总量，供调试/自检用。 */
export function registeredIconCount(): number {
  return Object.keys(iconsData.icons).length;
}

